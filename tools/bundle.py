"""Bundle the actual pinned Gen2 source with ModuleScript-relative require semantics.
Sources are embedded verbatim, including MPL notices. No minification or remote Lua loader.
"""
from pathlib import Path
import json, xml.etree.ElementTree as ET
from brand_assets import generate
generate()

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "dist"
OUT.mkdir(exist_ok=True)
nodes = []

def add(name, kind, parent, source=None):
    node = {"id": len(nodes) + 1, "name": name, "class": kind, "parent": parent, "source": source}
    nodes.append(node)
    return node["id"]

root = add("ConexaoUI", "ModuleScript", 0, ROOT / "ConexaoUI/init.luau")

def directory(path, parent, name):
    init = path / "init.luau"
    current = add(name, "ModuleScript" if init.exists() else "Folder", parent, init if init.exists() else None)
    for entry in sorted(path.iterdir()):
        if entry.is_dir(): directory(entry, current, entry.name)
        elif entry.suffix == ".luau" and entry.name != "init.luau": add(entry.stem, "ModuleScript", current, entry)
    return current

directory(ROOT / "vendor/rayfield-gen2/src", root, "Gen2")
directory(ROOT / "ConexaoUI/Features", root, "Features")
header = '''-- Conexão UI 3.5.0 — Rayfield Gen2 fork (MPL-2.0).
-- Rayfield Gen2 Copyright (c) 2026 Corridon Capital.
-- Source, modifications and license: https://github.com/brasilrjroleplay1-ux/ui
-- See LICENSE and NOTICE.md. Generated by tools/bundle.py; source is not obfuscated.
local __nodes, __constructors, __cache, __loading = {}, {}, {}, {}
local __methods = {}
function __methods:FindFirstChild(name) return self._children[name] end
function __methods:WaitForChild(name) return assert(self._children[name], "Missing module child: "..name) end
function __methods:GetChildren()
 local out={} for _,child in pairs(self._children) do table.insert(out,child) end
 table.sort(out,function(a,b) return a.Name<b.Name end) return out
end
function __methods:GetDescendants()
 local out={} for _,child in ipairs(self:GetChildren()) do table.insert(out,child) for _,desc in ipairs(child:GetDescendants()) do table.insert(out,desc) end end return out
end
function __methods:GetFullName() return (self.Parent and self.Parent:GetFullName().."." or "")..self.Name end
function __methods:IsA(class) return self.ClassName==class or class=="Instance" end
local __mt={__index=function(self,key) return __methods[key] or self._children[key] end}
local function __require(node)
 assert(type(node)=="table" and __constructors[node._id], "Expected a bundled ModuleScript")
 local id=node._id
 if __cache[id]~=nil then return __cache[id] end
 assert(not __loading[id],"Circular module dependency: "..node:GetFullName())
 __loading[id]=true
 local value=__constructors[id](node,__require)
 __loading[id]=nil
 assert(value~=nil,"Module returned nil: "..node:GetFullName())
 __cache[id]=value return value
end
'''
chunks = [header]
for node in nodes:
    chunks.append(f'__nodes[{node["id"]}]=setmetatable({{_id={node["id"]},Name={json.dumps(node["name"])},ClassName={json.dumps(node["class"])},_children={{}}}},__mt)\n')
for node in nodes:
    if node["parent"]:
        chunks.append(f'__nodes[{node["id"]}].Parent=__nodes[{node["parent"]}] __nodes[{node["parent"]}]._children[{json.dumps(node["name"])}]=__nodes[{node["id"]}]\n')
for node in nodes:
    if node["source"]:
        chunks.append(f'\n__constructors[{node["id"]}]=function(script,require)\n{node["source"].read_text()}\nend\n')
body = "".join(chunks)
(OUT / "ConexaoUI.luau").write_text(body + '\nreturn __require(__nodes[1])\n')
for name in ["Demo", "Minimal", "Components"]:
    example = (ROOT / f"ConexaoUI/Examples/{name}.client.luau").read_text()
    line = 'local UI = require(game:GetService("ReplicatedStorage"):WaitForChild("ConexaoUI"))'
    assert line in example
    (OUT / f"{name}.luau").write_text(body + '\n' + example.replace(line, 'local UI=__require(__nodes[1])', 1))

model = ET.Element("roblox", version="4")
items = {}
for node in nodes:
    parent = items[node["parent"]] if node["parent"] else model
    item = ET.SubElement(parent, "Item", {"class": node["class"]})
    props = ET.SubElement(item, "Properties")
    ET.SubElement(props, "string", name="Name").text = node["name"]
    if node["source"]: ET.SubElement(props, "ProtectedString", name="Source").text = node["source"].read_text()
    items[node["id"]] = item
ET.ElementTree(model).write(OUT / "ConexaoUI.rbxmx", encoding="utf-8", xml_declaration=True)
print(f'Bundled {sum(n["source"] is not None for n in nodes)} modules; generated library, clean demo, components, minimal and Studio model.')
