"""Bundle local Luau modules, without network dependencies or a fake script tree."""
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'ConexaoUI'
OUT = ROOT / 'dist'
modules = {p.relative_to(SRC).with_suffix('').as_posix():p for p in SRC.rglob('*.luau') if 'Examples' not in p.parts}
def resolve(current, expression):
    parts = expression.split('.')[1:]
    # init.luau is the package ModuleScript itself; other modules are file nodes.
    path = [] if current == 'init' else current.split('/')
    for part in parts:
        if part == 'Parent':
            if not path: raise ValueError(expression)
            path.pop()
        else: path.append(part)
    key = '/'.join(path)
    if key not in modules: raise ValueError(f'{current}: missing {key}')
    return f'__require("{key}")'
chunks = ['-- Conexão UI: generated by tools/bundle.py. No external runtime dependencies.\nlocal __modules, __cache = {}, {}\nlocal function __require(id)\n if __cache[id] ~= nil then return __cache[id] end\n assert(__modules[id], "Missing module: "..id)\n local result=__modules[id]()\n __cache[id]=result\n return result\nend\n']
for key, path in sorted(modules.items()):
    source = re.sub(r'require\((script(?:\.[A-Za-z_][A-Za-z_0-9]*)+)\)', lambda m:resolve(key,m[1]), path.read_text())
    chunks.append(f'__modules["{key}"] = function()\n{source}\nend\n')
body = '\n'.join(chunks)
OUT.mkdir(exist_ok=True)
(OUT/'ConexaoUI.luau').write_text(body+'\nreturn __require("init")\n')
demo=(SRC/'Examples/Demo.client.luau').read_text()
demo=re.sub(r"local UI=require\(game:GetService\('ReplicatedStorage'\):WaitForChild\('ConexaoUI'\)\)", 'local UI=__require("init")',demo)
(OUT/'Demo.luau').write_text(body+'\n'+demo)
print(f'Bundled {len(modules)} modules into dist/ConexaoUI.luau and dist/Demo.luau')
# Native Studio model: package ModuleScript, child folders/modules, embedded source.
import xml.etree.ElementTree as ET
model=ET.Element('roblox',version='4')
def item(parent, kind, name, source=None):
    node=ET.SubElement(parent,'Item',{'class':kind})
    properties=ET.SubElement(node,'Properties')
    ET.SubElement(properties,'string',name='Name').text=name
    if source is not None: ET.SubElement(properties,'ProtectedString',name='Source').text=source
    return node
package=item(model,'ModuleScript','ConexaoUI',modules['init'].read_text())
folders={}
for key,path in sorted(modules.items()):
    if key=='init': continue
    parts=key.split('/')
    parent=package
    for index,part in enumerate(parts[:-1]):
        name='/'.join(parts[:index+1])
        if name not in folders: folders[name]=item(parent,'Folder',part)
        parent=folders[name]
    item(parent,'ModuleScript',parts[-1],path.read_text())
ET.ElementTree(model).write(OUT/'ConexaoUI.rbxmx',encoding='utf-8',xml_declaration=True)

minimal=(SRC/'Examples/Minimal.client.luau').read_text()
minimal=re.sub(r"local UI=require\(game:GetService\('ReplicatedStorage'\):WaitForChild\('ConexaoUI'\)\)", 'local UI=__require("init")',minimal)
(OUT/'Minimal.luau').write_text(body+'\n'+minimal)
